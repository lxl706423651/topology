#!/usr/bin/env python3
"""Build SeedEMU Docker Compose images through a fast Docker archive path.

Purpose: create Docker-compatible image archives from compiled SeedEMU
per-node build contexts instead of running thousands of independent Docker
builds.
Inputs: output/docker-compose.yml and the Dockerfiles/build contexts referenced
by that Compose file.
Outputs: logs/dockerBuild/dockerBuild_*.log and output/.fastDockerBuild/*.
Side effects: pulls/builds shared base images, writes a Docker archive, and
loads generated image tags into the local Docker image store by default.
Context: run from the topology directory after SeedEMU has compiled ./output.
"""

from __future__ import annotations

import argparse
import copy
from dataclasses import dataclass
import hashlib
import io
import json
import os
from pathlib import Path
import posixpath
import re
import shutil
import shlex
import subprocess
import sys
import tarfile
import time
from typing import IO, Iterable

import yaml


Instruction = tuple[str, str, str]


@dataclass
class BuildEntry:
    service: str
    image: str
    context: Path
    dockerfile: Path


@dataclass
class DockerfilePlan:
    prefix: list[str]
    copies: list[tuple[str, str]]
    executable_targets: set[str]
    cmd: object


@dataclass
class FastImageEntry:
    build: BuildEntry
    plan: DockerfilePlan
    base_tag: str


@dataclass
class BaseArchiveInfo:
    directory: Path
    config: dict
    layers: list[str]


class TeeStream:
    """Write command output to the terminal and to the build log."""

    def __init__(self, *streams: IO[str]) -> None:
        self.streams = streams

    def write(self, data: str) -> int:
        for stream in self.streams:
            stream.write(data)
            stream.flush()
        return len(data)

    def flush(self) -> None:
        for stream in self.streams:
            stream.flush()


def sha256Bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def logInfo(message: str) -> None:
    print(f"[{time.strftime('%Y-%m-%d %H:%M:%S')}] {message}", flush=True)


def runCommand(cmd: list[str], *, stdout=None) -> None:
    print("+ " + " ".join(shlex.quote(part) for part in cmd), flush=True)
    subprocess.run(cmd, check=True, stdout=stdout)


def requireCommand(command_name: str) -> None:
    """Fail early when a required executable is missing from PATH."""

    if shutil.which(command_name) is None:
        raise RuntimeError(f"missing required command: {command_name}")


def checkDockerImageExists(image: str) -> bool:
    return (
        subprocess.run(
            ["docker", "image", "inspect", image],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            check=False,
        ).returncode
        == 0
    )


def renderMirrorImageName(image: str) -> str:
    mirror = os.environ.get("SEED_DOCKER_IO_MIRROR_ENDPOINT", "https://docker.m.daocloud.io")
    if not mirror:
        return image
    mirror_host = mirror.removeprefix("https://").removeprefix("http://").rstrip("/")
    if "/" in image:
        return f"{mirror_host}/{image}"
    return f"{mirror_host}/library/{image}"


def ensureSourceImage(image: str) -> None:
    """Ensure a non-local source image exists, using the configured mirror first."""

    if checkDockerImageExists(image):
        return
    mirror = renderMirrorImageName(image)
    if mirror != image:
        if subprocess.run(["docker", "pull", mirror], check=False).returncode == 0:
            runCommand(["docker", "tag", mirror, image])
            return
    runCommand(["docker", "pull", image])


def joinDockerfileLines(text: str) -> Iterable[str]:
    """Yield logical Dockerfile instruction lines after joining continuations."""

    pending = ""
    for raw_line in text.splitlines():
        line = raw_line.rstrip()
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.endswith("\\"):
            pending += stripped[:-1] + " "
            continue
        yield pending + stripped
        pending = ""
    if pending:
        yield pending.strip()


def parseDockerfile(path: Path) -> list[Instruction]:
    """Parse the limited Dockerfile grammar generated by SeedEMU."""

    instructions: list[Instruction] = []
    for line in joinDockerfileLines(path.read_text(encoding="utf-8")):
        match = re.match(r"^([A-Za-z]+)\s+(.*)$", line)
        if not match:
            raise RuntimeError(f"cannot parse Dockerfile line in {path}: {line}")
        op = match.group(1).upper()
        arg = match.group(2).strip()
        instructions.append((op, arg, line))
    return instructions


def iterDockerfileBaseImages(path: Path) -> Iterable[str]:
    for op, arg, _line in parseDockerfile(path):
        if op == "FROM":
            fields = shlex.split(arg)
            if fields:
                yield fields[0]


def parseCopyInstruction(arg: str) -> tuple[str, str]:
    fields = [field for field in shlex.split(arg) if not field.startswith("--")]
    if len(fields) != 2:
        raise RuntimeError(f"only simple two-argument COPY is supported: COPY {arg}")
    return fields[0], fields[1]


def parseCmdInstruction(arg: str) -> object:
    if arg.startswith("["):
        return json.loads(arg)
    return ["/bin/sh", "-c", arg]


def parseChmodTargets(arg: str) -> list[str]:
    """Return target paths for simple chmod commands emitted after COPY."""

    try:
        fields = shlex.split(arg)
    except ValueError:
        return []
    if len(fields) < 3 or fields[0] != "chmod":
        return []
    mode_index = 1
    while mode_index < len(fields) and fields[mode_index].startswith("-"):
        mode_index += 1
    return fields[mode_index + 1 :]


def normalizeArchivePath(path: str) -> str:
    normalized = posixpath.normpath(path)
    if normalized == ".":
        raise RuntimeError(f"invalid archive path: {path}")
    return normalized.lstrip("/")


def resolveCopyDestination(src: str, dest: str) -> str:
    if dest.endswith("/"):
        dest = posixpath.join(dest, posixpath.basename(src))
    return normalizeArchivePath(dest)


def createDockerfilePlan(instructions: list[Instruction]) -> DockerfilePlan:
    """Split a Dockerfile into a shared prefix and per-node copied files."""

    prefix: list[str] = []
    copies: list[tuple[str, str]] = []
    executable_targets: set[str] = set()
    cmd: object | None = None
    saw_copy = False

    for op, arg, line in instructions:
        if op == "COPY":
            saw_copy = True
            copies.append(parseCopyInstruction(arg))
            continue
        if not saw_copy:
            prefix.append(line)
            continue
        if op == "RUN":
            chmod_targets = parseChmodTargets(arg)
            if not chmod_targets:
                raise RuntimeError(f"unsupported RUN after COPY: {line}")
            executable_targets.update(normalizeArchivePath(target) for target in chmod_targets)
        elif op == "CMD":
            cmd = parseCmdInstruction(arg)
        elif op in {"LABEL", "ENV"}:
            continue
        else:
            raise RuntimeError(f"unsupported instruction after COPY: {line}")

    if not prefix or not prefix[0].upper().startswith("FROM "):
        raise RuntimeError("Dockerfile must start with FROM")
    if not copies:
        raise RuntimeError("Dockerfile has no COPY instructions")
    return DockerfilePlan(prefix=prefix, copies=copies, executable_targets=executable_targets, cmd=cmd or [])


def loadCompose(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as handle:
        data = yaml.safe_load(handle)
    if not isinstance(data, dict):
        raise RuntimeError(f"invalid compose file: {path}")
    services = data.get("services")
    if not isinstance(services, dict) or not services:
        raise RuntimeError(f"compose file has no services: {path}")
    return data


def resolveComposeProjectName(compose_file: Path, compose_data: dict) -> str:
    env_name = os.environ.get("COMPOSE_PROJECT_NAME", "").strip()
    if env_name:
        return env_name
    name = str(compose_data.get("name", "")).strip()
    if name:
        return name
    return compose_file.parent.name


def resolveBuildSpecPaths(compose_dir: Path, build_spec: object) -> tuple[Path, str]:
    if isinstance(build_spec, str):
        return (compose_dir / build_spec).resolve(), "Dockerfile"
    if isinstance(build_spec, dict):
        context = build_spec.get("context", ".")
        dockerfile = build_spec.get("dockerfile", "Dockerfile")
        return (compose_dir / str(context)).resolve(), str(dockerfile)
    raise RuntimeError(f"unsupported build spec: {build_spec!r}")


def resolveImageName(project_name: str, service_name: str, service: dict) -> str:
    image = str(service.get("image", "")).strip()
    if image:
        return image
    return f"{project_name}-{service_name}"


def dockerArchiveRepoTag(image: str) -> str:
    """Return a docker-load manifest RepoTag with an explicit tag component."""

    image = image.strip()
    if not image:
        raise RuntimeError("empty image name")
    if "@" in image:
        return image
    last_component = image.rsplit("/", 1)[-1]
    if ":" in last_component:
        return image
    return f"{image}:latest"


def discoverBuildEntries(
    compose_file: Path,
    skip_services: Iterable[str] = (),
) -> tuple[str, list[BuildEntry], dict[str, BuildEntry]]:
    """Read build contexts and final image tags from docker-compose.yml."""

    compose_data = loadCompose(compose_file)
    compose_dir = compose_file.parent.resolve()
    project_name = resolveComposeProjectName(compose_file, compose_data)
    entries: list[BuildEntry] = []
    by_tag: dict[str, BuildEntry] = {}
    skip_set = set(skip_services)

    for service_name, service in compose_data["services"].items():
        if str(service_name) in skip_set:
            continue
        if not isinstance(service, dict) or "build" not in service:
            continue
        context_dir, dockerfile_name = resolveBuildSpecPaths(compose_dir, service["build"])
        dockerfile_path = (context_dir / dockerfile_name).resolve()
        if not dockerfile_path.exists():
            raise RuntimeError(f"missing Dockerfile for service {service_name}: {dockerfile_path}")
        image = resolveImageName(project_name, str(service_name), service)
        entry = BuildEntry(str(service_name), image, context_dir, dockerfile_path)
        entries.append(entry)
        by_tag[image] = entry

    if not entries:
        raise RuntimeError("no buildable compose services found")
    return project_name, entries, by_tag


def writeBuildImagesFile(path: Path, compose_dir: Path, entries: list[BuildEntry]) -> None:
    """Write a build_images.sh-compatible mapping for debugging and reuse."""

    path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    for entry in entries:
        try:
            context_ref: Path | str = entry.context.relative_to(compose_dir)
        except ValueError:
            context_ref = entry.context
        lines.append(f"seedemu_build_and_push {entry.image} {context_ref}\n")
    path.write_text("".join(lines), encoding="utf-8")
    path.chmod(0o755)


def buildImageEntry(entry: BuildEntry) -> None:
    """Build one image normally, used for base-only contexts."""

    for source in iterDockerfileBaseImages(entry.dockerfile):
        ensureSourceImage(source)
    runCommand(["docker", "build", "-t", entry.image, "-f", str(entry.dockerfile), str(entry.context)])


def ensureImageAvailable(image: str, by_tag: dict[str, BuildEntry]) -> None:
    if image in by_tag:
        if not checkDockerImageExists(image):
            buildImageEntry(by_tag[image])
    elif not checkDockerImageExists(image):
        ensureSourceImage(image)


def buildCommonBaseImage(prefix: list[str], by_tag: dict[str, BuildEntry], base_root: Path) -> str:
    """Build the Dockerfile section shared by many SeedEMU node images once."""

    digest = sha256Bytes(("\n".join(prefix) + "\n").encode("utf-8"))[:24]
    tag = f"seedemu-fast-base:{digest}"
    if checkDockerImageExists(tag):
        return tag
    context_dir = base_root / digest
    context_dir.mkdir(parents=True, exist_ok=True)
    dockerfile = context_dir / "Dockerfile"
    dockerfile.write_text("\n".join(prefix) + "\n", encoding="utf-8")
    for source in iterDockerfileBaseImages(dockerfile):
        ensureImageAvailable(source, by_tag)
    runCommand(["docker", "build", "-t", tag, str(context_dir)])
    return tag


def extractImageArchive(image: str, dest: Path) -> None:
    """Save one Docker image and unpack its archive into a reusable cache."""

    marker = dest / ".ready"
    if marker.exists() and marker.read_text(encoding="utf-8").strip() == image:
        return
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    proc = subprocess.Popen(["docker", "save", image], stdout=subprocess.PIPE)
    assert proc.stdout is not None
    try:
        with tarfile.open(fileobj=proc.stdout, mode="r|") as archive:
            archive.extractall(dest)
    finally:
        rc = proc.wait()
    if rc != 0:
        raise RuntimeError(f"docker save failed for {image} with exit code {rc}")
    marker.write_text(f"{image}\n", encoding="utf-8")


def loadBaseArchive(base_dir: Path) -> tuple[dict, list[str]]:
    manifest = json.loads((base_dir / "manifest.json").read_text(encoding="utf-8"))
    if not manifest:
        raise RuntimeError(f"empty manifest in {base_dir}")
    entry = manifest[0]
    config = json.loads((base_dir / entry["Config"]).read_text(encoding="utf-8"))
    layers = list(entry["Layers"])
    for layer in layers:
        if not (base_dir / layer).exists():
            raise RuntimeError(f"missing base layer {layer}")
    return config, layers


def addArchiveDirectory(archive: tarfile.TarFile, name: str, added: set[str]) -> None:
    name = normalizeArchivePath(name).rstrip("/")
    if not name or name in added:
        return
    parent = posixpath.dirname(name)
    if parent:
        addArchiveDirectory(archive, parent, added)
    info = tarfile.TarInfo(name + "/")
    info.type = tarfile.DIRTYPE
    info.mode = 0o755
    info.uid = 0
    info.gid = 0
    info.uname = "root"
    info.gname = "root"
    info.mtime = 0
    archive.addfile(info)
    added.add(name)


def addArchiveBytes(
    archive: tarfile.TarFile,
    name: str,
    data: bytes,
    mode: int,
    added: set[str],
) -> None:
    name = normalizeArchivePath(name)
    if name in added:
        return
    parent = posixpath.dirname(name)
    if parent:
        addArchiveDirectory(archive, parent, added)
    info = tarfile.TarInfo(name)
    info.size = len(data)
    info.mode = mode
    info.uid = 0
    info.gid = 0
    info.uname = "root"
    info.gname = "root"
    info.mtime = 0
    archive.addfile(info, io.BytesIO(data))
    added.add(name)


def addArchiveFileOnce(archive: tarfile.TarFile, src: Path, arcname: str, added: set[str]) -> None:
    arcname = normalizeArchivePath(arcname)
    if arcname in added:
        return
    archive.add(src, arcname=arcname, recursive=False)
    added.add(arcname)


def createRuntimeLayer(context_dir: Path, plan: DockerfilePlan) -> tuple[str, bytes]:
    """Create the per-node layer that contains copied SeedEMU config files."""

    buffer = io.BytesIO()
    added: set[str] = set()
    with tarfile.open(fileobj=buffer, mode="w") as archive:
        for src_name, dest_name in plan.copies:
            src = (context_dir / src_name).resolve()
            if not src.exists() or not src.is_file():
                raise RuntimeError(f"missing COPY source: {src}")
            archive_path = resolveCopyDestination(src_name, dest_name)
            mode = src.stat().st_mode & 0o777
            if mode == 0:
                mode = 0o644
            if archive_path in plan.executable_targets:
                mode |= 0o111
            addArchiveBytes(archive, archive_path, src.read_bytes(), mode, added)
    data = buffer.getvalue()
    return sha256Bytes(data), data


def createImageConfig(base_config: dict, layer_diff_id: str, cmd: object) -> tuple[str, bytes]:
    config = copy.deepcopy(base_config)
    config.setdefault("config", {})
    if cmd:
        config["config"]["Cmd"] = cmd
    config.setdefault("rootfs", {}).setdefault("diff_ids", [])
    config["rootfs"]["diff_ids"] = list(config["rootfs"]["diff_ids"]) + [f"sha256:{layer_diff_id}"]
    history = list(config.get("history", []))
    history.append(
        {
            "created_by": "buildFastDockerImages.py",
            "comment": "SeedEMU runtime configuration layer",
        }
    )
    config["history"] = history
    data = json.dumps(config, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return sha256Bytes(data), data


def writeDockerArchive(
    archive_path: Path,
    images: list[FastImageEntry],
    base_info: dict[str, BaseArchiveInfo],
) -> list[dict]:
    """Write one docker-loadable archive containing all fast-path image tags."""

    archive_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_entries = []
    layer_cache: dict[str, tuple[str, bytes]] = {}
    config_cache: dict[str, bytes] = {}
    added_paths: set[str] = set()
    results = []

    with tarfile.open(archive_path, mode="w") as output:
        for info in base_info.values():
            for layer in info.layers:
                addArchiveFileOnce(output, info.directory / layer, layer, added_paths)

        for entry in images:
            base = base_info[entry.base_tag]
            copy_key = json.dumps(entry.plan.copies, sort_keys=True)
            layer_key = f"{entry.build.context}|{copy_key}"
            if layer_key in layer_cache:
                layer_diff_id, layer_data = layer_cache[layer_key]
            else:
                layer_diff_id, layer_data = createRuntimeLayer(entry.build.context, entry.plan)
                layer_cache[layer_key] = (layer_diff_id, layer_data)
            layer_path = f"blobs/sha256/{layer_diff_id}"
            addArchiveBytes(output, layer_path, layer_data, 0o444, added_paths)

            config_digest, config_data = createImageConfig(base.config, layer_diff_id, entry.plan.cmd)
            config_path = f"blobs/sha256/{config_digest}"
            if config_digest not in config_cache:
                config_cache[config_digest] = config_data
                addArchiveBytes(output, config_path, config_data, 0o444, added_paths)
            manifest_entries.append(
                {
                    "Config": config_path,
                    "RepoTags": [dockerArchiveRepoTag(entry.build.image)],
                    "Layers": base.layers + [layer_path],
                }
            )
            results.append(
                {
                    "service": entry.build.service,
                    "image": entry.build.image,
                    "archiveRepoTag": dockerArchiveRepoTag(entry.build.image),
                    "base": entry.base_tag,
                }
            )

        addArchiveBytes(
            output,
            "manifest.json",
            json.dumps(manifest_entries, indent=2).encode("utf-8"),
            0o644,
            added_paths,
        )
    return results


def createFastArchive(
    *,
    compose_file: Path,
    archive_file: Path,
    summary_file: Path,
    build_images_file: Path,
    cache_dir: Path,
    skip_services: Iterable[str] = (),
) -> dict:
    """Build common bases and write the final fast-path Docker archive."""

    started = time.monotonic()
    base_context_root = cache_dir / "common_base_contexts"
    base_archive_root = cache_dir / "common_base_archives"
    shutil.rmtree(base_context_root, ignore_errors=True)
    base_context_root.mkdir(parents=True, exist_ok=True)
    base_archive_root.mkdir(parents=True, exist_ok=True)

    skipped_services = sorted(set(skip_services))
    project_name, entries, by_tag = discoverBuildEntries(compose_file, skipped_services)
    writeBuildImagesFile(build_images_file, compose_file.parent.resolve(), entries)

    fast_images: list[FastImageEntry] = []
    normal_images: list[BuildEntry] = []
    prefix_to_base: dict[str, str] = {}

    for entry in entries:
        instructions = parseDockerfile(entry.dockerfile)
        try:
            plan = createDockerfilePlan(instructions)
        except RuntimeError as exc:
            if "has no COPY instructions" not in str(exc):
                raise
            logInfo(f"Building base-only service normally: {entry.service}")
            buildImageEntry(entry)
            normal_images.append(entry)
            continue
        prefix_key = sha256Bytes(("\n".join(plan.prefix) + "\n").encode("utf-8"))
        if prefix_key not in prefix_to_base:
            prefix_to_base[prefix_key] = buildCommonBaseImage(plan.prefix, by_tag, base_context_root)
        fast_images.append(FastImageEntry(entry, plan, prefix_to_base[prefix_key]))

    if not fast_images:
        raise RuntimeError("no COPY-based service images found for fast archive generation")

    base_info: dict[str, BaseArchiveInfo] = {}
    for tag in sorted({entry.base_tag for entry in fast_images}):
        digest = tag.split(":", 1)[1]
        archive_dir = base_archive_root / digest
        extractImageArchive(tag, archive_dir)
        config, layers = loadBaseArchive(archive_dir)
        base_info[tag] = BaseArchiveInfo(archive_dir, config, layers)

    results = writeDockerArchive(archive_file, fast_images, base_info)
    summary = {
        "status": "PASS",
        "projectName": project_name,
        "composeFile": str(compose_file),
        "archive": str(archive_file),
        "archiveBytes": archive_file.stat().st_size,
        "imageCount": len(results),
        "normalImageCount": len(normal_images),
        "baseCount": len(base_info),
        "servicesSkipped": len(skipped_services),
        "skippedServices": skipped_services,
        "durationSeconds": round(time.monotonic() - started, 2),
        "images": results[:20],
    }
    summary_file.parent.mkdir(parents=True, exist_ok=True)
    summary_file.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    return summary


def parseArgs() -> argparse.Namespace:
    repo_dir = Path(__file__).resolve().parent
    default_compose = repo_dir / "output" / "docker-compose.yml"
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "compose_file",
        nargs="?",
        default=default_compose,
        type=Path,
        help="Path to output/docker-compose.yml.",
    )
    parser.add_argument(
        "--work-dir",
        type=Path,
        help="Generated working directory. Defaults to <compose-dir>/.fastDockerBuild.",
    )
    parser.add_argument(
        "--log-dir",
        type=Path,
        default=repo_dir / "logs" / "dockerBuild",
        help="Directory for dockerBuild_*.log.",
    )
    parser.add_argument(
        "--skip-load",
        action="store_true",
        help="Create the Docker archive but do not run docker load.",
    )
    parser.add_argument(
        "--skip-service",
        action="append",
        default=[],
        help="Compose service name to exclude from fast archive generation. Can be repeated.",
    )
    return parser.parse_args()


def main() -> int:
    args = parseArgs()
    requireCommand("docker")

    started = time.time()
    compose_file = args.compose_file.expanduser().resolve()
    if not compose_file.is_file():
        raise RuntimeError(f"missing compose file: {compose_file}")
    output_dir = compose_file.parent
    work_dir = (args.work_dir or (output_dir / ".fastDockerBuild")).expanduser().resolve()
    archive_file = work_dir / "images_all.tar"
    summary_file = work_dir / "summary.json"
    build_images_file = work_dir / "build_images.sh"
    log_dir = args.log_dir.expanduser().resolve()
    log_dir.mkdir(parents=True, exist_ok=True)
    work_dir.mkdir(parents=True, exist_ok=True)
    log_file = log_dir / f"dockerBuild_{time.strftime('%Y%m%d_%H%M%S')}.log"

    with log_file.open("w", encoding="utf-8") as log_handle:
        original_stdout = sys.stdout
        original_stderr = sys.stderr
        sys.stdout = TeeStream(original_stdout, log_handle)  # type: ignore[assignment]
        sys.stderr = TeeStream(original_stderr, log_handle)  # type: ignore[assignment]
        try:
            logInfo("===== Fast SeedEMU Docker build started =====")
            logInfo(f"Compose file: {compose_file}")
            logInfo(f"Output directory: {output_dir}")
            logInfo(f"Generated work directory: {work_dir}")
            runCommand(["du", "-sh", str(output_dir)])

            os.environ["DOCKER_BUILDKIT"] = "1"
            os.environ["COMPOSE_DOCKER_CLI_BUILD"] = "1"

            summary = createFastArchive(
                compose_file=compose_file,
                archive_file=archive_file,
                summary_file=summary_file,
                build_images_file=build_images_file,
                cache_dir=work_dir / "cache",
                skip_services=args.skip_service,
            )
            logInfo(
                f"Wrote {summary['imageCount']} fast images across {summary['baseCount']} "
                f"common bases to {archive_file}"
            )

            if args.skip_load:
                logInfo("Skipping docker load because --skip-load was set.")
            else:
                logInfo("Loading generated image archive into local Docker...")
                runCommand(["docker", "load", "-i", str(archive_file)])

            duration = int(time.time() - started)
            hours = duration // 3600
            minutes = (duration % 3600) // 60
            seconds = duration % 60
            logInfo("Fast build completed.")
            logInfo(f"Archive: {archive_file}")
            logInfo(f"Summary: {summary_file}")
            logInfo(f"Generated build_images mapping: {build_images_file}")
            logInfo(f"Total runtime: {hours}h {minutes}m {seconds}s")
            logInfo(f"Full log saved to: {log_file}")
        finally:
            sys.stdout = original_stdout
            sys.stderr = original_stderr
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        raise SystemExit(1)
