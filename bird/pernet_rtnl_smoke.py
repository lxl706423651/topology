#!/usr/bin/env python3
"""Smoke-test the standard IPv4 per-netns RTNL route-update path.

The test uses only standard RTM_NEWROUTE/RTM_DELROUTE operations generated by
``ip -batch``.  Kprobe events distinguish two properties that are otherwise
easy to conflate:

* whether the rtnl_net_lock() path is active; and
* whether fib_table_insert() actually overlaps across worker namespaces.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time


RISK_RE = re.compile(
    r"BUG:|Oops|panic|WARNING:|lockdep|KASAN|refcount|use-after-free|"
    r"general protection|soft lockup|hung task|ASSERT_RTNL|RTNL_NET",
    re.IGNORECASE,
)
TRACE_EVENT_RE = re.compile(
    r"-(?P<pid>\d+)\s+\[(?P<cpu>\d+)\].*?\s(?P<ts>\d+\.\d+):\s+"
    r"(?P<event>insert_enter|insert_exit|net_lock):"
)


class SmokeError(RuntimeError):
    pass


def now_iso() -> str:
    return dt.datetime.now(dt.timezone.utc).astimezone().isoformat(timespec="seconds")


def run(
    cmd: list[str],
    *,
    timeout: float | None = None,
    check: bool = False,
    input_text: str | None = None,
) -> subprocess.CompletedProcess:
    proc = subprocess.run(cmd, text=True, capture_output=True, timeout=timeout, input=input_text)
    if check and proc.returncode != 0:
        message = (proc.stderr or proc.stdout or "command failed").strip()
        raise SmokeError(f"{' '.join(cmd)}: {message[-3000:]}")
    return proc


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    tmp.replace(path)


def kernel_config() -> dict:
    release = os.uname().release
    candidates = [Path(f"/boot/config-{release}"), Path("/proc/config.gz")]
    text = ""
    source = None
    for candidate in candidates:
        if not candidate.exists():
            continue
        source = str(candidate)
        if candidate.suffix == ".gz":
            proc = run(["gzip", "-dc", str(candidate)], check=True)
            text = proc.stdout
        else:
            text = candidate.read_text(encoding="utf-8", errors="replace")
        break
    values = {}
    for key in [
        "CONFIG_DEBUG_NET_SMALL_RTNL",
        "CONFIG_PROVE_LOCKING",
        "CONFIG_KPROBES",
        "CONFIG_KPROBE_EVENTS",
        "CONFIG_FTRACE",
    ]:
        match = re.search(rf"^{re.escape(key)}=(.*)$", text, re.MULTILINE)
        values[key] = match.group(1) if match else "not-set"
    return {"source": source, "values": values}


def tracefs_path() -> Path | None:
    for path in [Path("/sys/kernel/tracing"), Path("/sys/kernel/debug/tracing")]:
        if (path / "kprobe_events").exists():
            return path
    return None


def trace_write(path: Path, value: str) -> None:
    path.write_text(value, encoding="utf-8")


def append_kprobe_event(tracefs: Path, value: str) -> None:
    fd = os.open(tracefs / "kprobe_events", os.O_WRONLY | os.O_APPEND)
    try:
        os.write(fd, value.encode("utf-8"))
    finally:
        os.close(fd)


def remove_probe(tracefs: Path, name: str) -> None:
    append_kprobe_event(tracefs, f"-:pernet_smoke/{name}\n")


def configure_probes(tracefs: Path) -> dict:
    trace_write(tracefs / "tracing_on", "0\n")
    for name in ["insert_enter", "insert_exit", "net_lock"]:
        try:
            remove_probe(tracefs, name)
        except OSError:
            pass
    available = (tracefs / "available_filter_functions").read_text(encoding="utf-8", errors="replace")
    if not re.search(r"^fib_table_insert(?:\s|$)", available, re.MULTILINE):
        raise SmokeError("fib_table_insert is unavailable for tracing")
    append_kprobe_event(tracefs, "p:pernet_smoke/insert_enter fib_table_insert\n")
    append_kprobe_event(tracefs, "r:pernet_smoke/insert_exit fib_table_insert\n")
    net_lock_available = bool(re.search(r"^rtnl_net_lock(?:\s|$)", available, re.MULTILINE))
    if net_lock_available:
        append_kprobe_event(tracefs, "p:pernet_smoke/net_lock rtnl_net_lock\n")
    # The trace pseudo-file is cleared by truncation.  Writing a newline is
    # rejected with EINVAL on some kernels.
    trace_write(tracefs / "trace", "")
    for name in ["insert_enter", "insert_exit"]:
        trace_write(tracefs / "events" / "pernet_smoke" / name / "enable", "1\n")
    if (tracefs / "events" / "pernet_smoke" / "net_lock" / "enable").exists():
        trace_write(tracefs / "events" / "pernet_smoke" / "net_lock" / "enable", "1\n")
    trace_write(tracefs / "tracing_on", "1\n")
    return {"tracefs": str(tracefs), "rtnl_net_lock_probe": net_lock_available}


def stop_probes(tracefs: Path) -> str:
    trace_write(tracefs / "tracing_on", "0\n")
    text = (tracefs / "trace").read_text(encoding="utf-8", errors="replace")
    for name in ["insert_enter", "insert_exit", "net_lock"]:
        enable = tracefs / "events" / "pernet_smoke" / name / "enable"
        if enable.exists():
            try:
                trace_write(enable, "0\n")
            except OSError:
                pass
        try:
            remove_probe(tracefs, name)
        except OSError:
            pass
    return text


def parse_trace(text: str, worker_pids: set[int]) -> dict:
    events = []
    for line in text.splitlines():
        match = TRACE_EVENT_RE.search(line)
        if not match:
            continue
        row = {
            "pid": int(match.group("pid")),
            "cpu": int(match.group("cpu")),
            "timestamp": float(match.group("ts")),
            "event": match.group("event"),
        }
        events.append(row)
    events.sort(key=lambda row: (row["timestamp"], 0 if row["event"] == "insert_exit" else 1))
    depth: dict[int, int] = {}
    max_active = 0
    overlap_examples = []
    enter_count = 0
    exit_count = 0
    net_lock_count = 0
    for row in events:
        pid = row["pid"]
        if row["event"] == "net_lock":
            if pid in worker_pids:
                net_lock_count += 1
            continue
        if pid not in worker_pids:
            continue
        if row["event"] == "insert_enter":
            enter_count += 1
            depth[pid] = depth.get(pid, 0) + 1
            active = sorted(key for key, value in depth.items() if value > 0)
            if len(active) > max_active:
                max_active = len(active)
                if len(active) > 1 and len(overlap_examples) < 20:
                    overlap_examples.append(
                        {"timestamp": row["timestamp"], "cpu": row["cpu"], "active_pids": active}
                    )
        else:
            exit_count += 1
            if depth.get(pid, 0) > 0:
                depth[pid] -= 1
    return {
        "worker_pids": sorted(worker_pids),
        "events_total": len(events),
        "fib_insert_enter_events": enter_count,
        "fib_insert_exit_events": exit_count,
        "rtnl_net_lock_events": net_lock_count,
        "max_concurrent_worker_fib_inserts": max_active,
        "cross_worker_overlap_detected": max_active > 1,
        "overlap_examples": overlap_examples,
    }


def route_prefix(ns_index: int, route_index: int) -> str:
    second = (ns_index % 200) + 20
    third = (route_index // 256) % 256
    fourth = route_index % 256
    return f"10.{second}.{third}.{fourth}/32"


def prepare_namespaces(prefix: str, count: int, routes: int, work_dir: Path) -> list[dict]:
    rows = []
    for index in range(count):
        name = f"{prefix}-{index}"
        run(["ip", "netns", "add", name], check=True)
        run(["ip", "-n", name, "link", "add", "dummy0", "type", "dummy"], check=True)
        run(["ip", "-n", name, "link", "set", "dummy0", "up"], check=True)
        batch = work_dir / f"routes-{index}.batch"
        batch.write_text(
            "".join(
                f"route replace {route_prefix(index, route)} dev dummy0 proto static metric 100\n"
                for route in range(1, routes + 1)
            ),
            encoding="utf-8",
        )
        rows.append({"index": index, "name": name, "batch": batch})
    return rows


def cleanup_namespaces(rows: list[dict]) -> None:
    for row in rows:
        run(["ip", "netns", "del", row["name"]])


def flush_routes(rows: list[dict]) -> None:
    for row in rows:
        run(["ip", "-n", row["name"], "route", "flush", "proto", "static"], timeout=120)


def run_sequential(rows: list[dict], command_timeout: float) -> dict:
    started = time.monotonic()
    failures = []
    for row in rows:
        proc = run(
            ["ip", "-n", row["name"], "-force", "-batch", str(row["batch"])],
            timeout=command_timeout,
        )
        if proc.returncode != 0:
            failures.append({"namespace": row["name"], "error": (proc.stderr or proc.stdout or "")[-2000:]})
    return {"seconds": round(time.monotonic() - started, 6), "failures": failures}


def run_parallel(rows: list[dict], command_timeout: float, tracefs: Path | None) -> tuple[dict, str]:
    trace_setup = None
    trace_error = None
    if tracefs:
        try:
            trace_setup = configure_probes(tracefs)
        except Exception as exc:
            trace_error = str(exc)
    started = time.monotonic()
    processes = []
    for row in rows:
        proc = subprocess.Popen(
            ["ip", "-n", row["name"], "-force", "-batch", str(row["batch"])],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
        processes.append((row, proc))
    worker_pids = {proc.pid for _, proc in processes}
    failures = []
    deadline = time.monotonic() + command_timeout
    for row, proc in processes:
        try:
            stdout, stderr = proc.communicate(timeout=max(0.1, deadline - time.monotonic()))
        except subprocess.TimeoutExpired:
            proc.kill()
            stdout, stderr = proc.communicate()
            failures.append({"namespace": row["name"], "error": "timeout"})
            continue
        if proc.returncode != 0:
            failures.append({"namespace": row["name"], "error": (stderr or stdout or "")[-2000:]})
    elapsed = time.monotonic() - started
    trace_text = ""
    if trace_setup and tracefs:
        try:
            trace_text = stop_probes(tracefs)
        except Exception as exc:
            trace_error = f"{trace_error or ''}; stop: {exc}".strip("; ")
    result = {
        "seconds": round(elapsed, 6),
        "failures": failures,
        "trace_setup": trace_setup,
        "trace_error": trace_error,
        "worker_pids": sorted(worker_pids),
    }
    return result, trace_text


def kernel_risk_log(since_epoch: int) -> dict:
    proc = run(["journalctl", "-k", "--since", f"@{since_epoch}", "--no-pager"], timeout=120)
    text = (proc.stdout or "") + "\n" + (proc.stderr or "")
    hits = [line for line in text.splitlines() if RISK_RE.search(line)]
    return {"returncode": proc.returncode, "hit_count": len(hits), "hits": hits[-100:]}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work-dir", type=Path, required=True)
    parser.add_argument("--namespaces", type=int, default=16)
    parser.add_argument("--routes-per-namespace", type=int, default=2000)
    parser.add_argument("--command-timeout", type=float, default=600.0)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if os.geteuid() != 0:
        print("ERROR: run with sudo", file=sys.stderr)
        return 2
    work_dir = args.work_dir.expanduser().resolve()
    work_dir.mkdir(parents=True, exist_ok=True)
    summary_path = work_dir / "summary.json"
    trace_path = work_dir / "kprobe.trace"
    started_epoch = int(time.time())
    started = time.monotonic()
    prefix = f"pernet-smoke-{os.getpid()}"
    rows: list[dict] = []
    summary = {
        "schema_version": 1,
        "started_at": now_iso(),
        "kernel_release": os.uname().release,
        "kernel_config": kernel_config(),
        "settings": vars(args) | {"work_dir": str(work_dir)},
        "success": None,
        "error": None,
    }
    write_json(summary_path, summary)
    try:
        rows = prepare_namespaces(prefix, args.namespaces, args.routes_per_namespace, work_dir)
        sequential = run_sequential(rows, args.command_timeout)
        flush_routes(rows)
        parallel, trace_text = run_parallel(rows, args.command_timeout, tracefs_path())
        trace_path.write_text(trace_text, encoding="utf-8")
        trace = parse_trace(trace_text, set(parallel["worker_pids"]))
        counts = []
        for row in rows:
            proc = run(["ip", "-n", row["name"], "route", "show", "proto", "static"], timeout=120)
            counts.append({"namespace": row["name"], "routes": len(proc.stdout.splitlines())})
        expected = args.routes_per_namespace
        count_ok = all(row["routes"] == expected for row in counts)
        risk = kernel_risk_log(started_epoch)
        sequential_seconds = sequential["seconds"]
        parallel_seconds = parallel["seconds"]
        trace_valid = (
            parallel["trace_error"] is None
            and trace["fib_insert_enter_events"] > 0
            and trace["fib_insert_exit_events"] > 0
        )
        summary.update(
            {
                "sequential": sequential,
                "parallel": parallel,
                "trace": trace,
                "route_counts": counts,
                "route_counts_ok": count_ok,
                "parallel_speedup": round(sequential_seconds / parallel_seconds, 6)
                if parallel_seconds > 0
                else None,
                "pernet_lock_path_observed": trace["rtnl_net_lock_events"] > 0,
                "true_cross_netns_fib_concurrency": trace["cross_worker_overlap_detected"],
                "trace_valid": trace_valid,
                "kernel_risk_log": risk,
                "success": not sequential["failures"]
                and not parallel["failures"]
                and count_ok
                and trace_valid
                and risk["hit_count"] == 0,
            }
        )
    except Exception as exc:
        summary["success"] = False
        summary["error"] = str(exc)
    finally:
        cleanup_namespaces(rows)
        summary["ended_at"] = now_iso()
        summary["duration_seconds"] = round(time.monotonic() - started, 3)
        write_json(summary_path, summary)
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    print(f"Summary: {summary_path}", flush=True)
    return 0 if summary.get("success") else 1


if __name__ == "__main__":
    raise SystemExit(main())
